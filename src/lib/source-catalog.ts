export const FREE_API_CATALOG: ApiSourceDefinition[] = BASE_FREE_API_CATALOG.map((source) => ({
  ...source,
  registry: "public-apis",
}));

export function catalogForRegions(regions: string[]): ApiSourceDefinition[] {
  const normalized = regions.map((item) => item.toUpperCase());
  return FREE_API_CATALOG.filter((source) =>
    source.regions.includes(GLOBAL) || source.regions.some((region) => normalized.includes(region)),
  );
}

export function ukStarterCatalog(): ApiSourceDefinition[] {
  return FREE_API_CATALOG.filter((source) => source.regions.includes("GB") || source.regions.includes(GLOBAL));
}
